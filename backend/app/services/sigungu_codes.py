def find_area_signgu(address: str) -> tuple[int, int] | None:
    """
    '경기도 수원시 팔달구 정조로 825' 같은 주소 문자열에서 (areaCd, signguCd)를 찾습니다.
    시군구명이 여러 단어(예: '수원시 팔달구')로 구성된 항목을 우선(더 구체적인 것부터)
    매칭하고, 못 찾으면 시/도 단위까지만이라도 맞는 후보를 반환합니다.
    """
    if not address:
        return None

    # 시군구명 길이(구체성) 내림차순으로 정렬해서, "수원시"보다 "수원시 팔달구"가
    # 먼저 매칭되도록 합니다.
    candidates = sorted(SIGUNGU_TABLE, key=lambda row: -len(row[3]))
    for area_cd, area_nm, signgu_cd, signgu_nm in candidates:
        # 시도명(예: '경기도')과 시군구명(예: '수원시 팔달구')이 모두 주소에 포함되는지 확인
        if area_nm.replace(" ", "") in address.replace(" ", "") and all(
            token in address for token in signgu_nm.split()
        ):
            return area_cd, signgu_cd
    return None


def list_signgu_by_area(area_nm: str) -> list[tuple[int, str]]:
    """
    '경기도' 같은 시/도 이름으로 그 안에 속한 시/군/구 목록을 [(signguCd, signguNm), ...]
    형태로 반환합니다 (지역 선택 UI에 사용). 가나다순으로 정렬됩니다.
    """
    rows = [
        (signgu_cd, signgu_nm)
        for area_cd, nm, signgu_cd, signgu_nm in SIGUNGU_TABLE
        if nm == area_nm
    ]
    return sorted(rows, key=lambda r: r[1])


def signgu_name(code: int) -> str | None:
    """법정동 시군구코드로 이름을 찾습니다 (예: 41115 -> '수원시 팔달구')."""
    for _, _, signgu_cd, signgu_nm in SIGUNGU_TABLE:
        if signgu_cd == code:
            return signgu_nm
    return None
