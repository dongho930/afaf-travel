/**
 * "앱에서 무언가를 바꾼 적이 있는지"를 세는 아주 단순한 카운터입니다.
 *
 * 화면을 열 때마다 굳이 다시 안 불러도 되는 값들(예: 내 여행 탭의 리뷰/제보/
 * 방문 개수)이 있습니다. 이 값들은 리뷰를 쓰거나 방문 처리를 했을 때만 바뀌는데,
 * 그 동작이 다른 화면(관광지 상세, 접근성 탭)에서 일어나기 때문에 "이 화면에서
 * 뭔가 했을 때만 갱신"하는 식으로는 최신 상태를 놓칩니다.
 *
 * 그래서 서버 상태를 바꾸는 요청(POST/PATCH/DELETE)이 나갈 때마다 이 숫자를
 * 하나 올리고(services/api.ts), 값을 쓰는 쪽은 "내가 마지막으로 받아온 뒤로
 * 숫자가 달라졌을 때만" 다시 불러오면 됩니다.
 *
 * 앱을 켜는 동안에만 유지되는 값이라, 앱을 새로 켜면 어차피 처음부터 불러옵니다.
 * 다른 기기에서 바꾼 내용은 감지하지 못하지만, 그건 화면을 새로 열거나 앱을
 * 다시 켜면 반영됩니다.
 */
let version = 0;

/** 서버 상태를 바꾸는 요청이 성공했을 때 호출합니다. */
export function bumpDataVersion(): void {
  version += 1;
}

/** 지금까지 몇 번 바뀌었는지. 이 값이 달라졌으면 다시 불러올 때가 된 것입니다. */
export function getDataVersion(): number {
  return version;
}
